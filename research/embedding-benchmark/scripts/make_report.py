"""Render results/summary.md from results/*.json."""
import json
from pathlib import Path

from models import MODELS, model_dir

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"


def mb(name, variant):
    files = MODELS[name]["variants"].get(variant)
    if not files:
        return "-"
    try:
        return f"{sum((model_dir(name) / f).stat().st_size for f in files) / 1e6:.0f}"
    except FileNotFoundError:
        return "?"


def f3(x):
    return f"{x:.3f}" if isinstance(x, float) else "-"


def main():
    out = ["# Embedding benchmark summary (auto-generated by make_report.py)", ""]
    out += ["## Models", "", "| model | params | dim | max tokens | ONNX fp32 MB | ONNX int8 MB | tokenizer | license |",
            "|---|---|---|---|---|---|---|---|"]
    for n, m in MODELS.items():
        out.append(f"| {n} | {m['params']} | {m['dim']} | {m['max_len']} | {mb(n, 'fp32')} | {mb(n, 'int8')} "
                   f"| {m['tokenizer']} | {m['license']} |")

    q = {}
    for p in sorted(RES.glob("quality_*.json")):
        r = json.loads(p.read_text())
        q[(r["model"], r["variant"])] = r
    out += ["", "## Quality", "",
            "conv = hand-made ja/en conversational set (50 queries, 2,136 segments). "
            "gov = JaGovFAQs-22k subset (150 q / 1,000 docs). JSTS = Spearman on 500 val pairs.", "",
            "| model | ONNX | vectors | conv R@1 | conv R@5 | conv R@10 | conv MRR@10 | gov R@1 | gov R@10 | gov MRR@10 | JSTS ρ |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for (n, v), r in q.items():
        for vec in ("fp32vec", "int8vec"):
            c, g = r.get(f"conv_{vec}", {}), r.get(f"gov_{vec}", {})
            out.append(f"| {n} | {v} | {vec} | {f3(c.get('R@1'))} | {f3(c.get('R@5'))} | {f3(c.get('R@10'))} "
                       f"| {f3(c.get('MRR@10'))} | {f3(g.get('R@1'))} | {f3(g.get('R@10'))} | {f3(g.get('MRR@10'))} "
                       f"| {f3(r.get('jsts_spearman')) if vec == 'fp32vec' else ''} |")
    types = ["ja_kw", "ja_para", "en", "x_ja2en", "x_en2ja"]
    out += ["", "### conv R@5 by query type (fp32 vectors)", "",
            "| model | ONNX | " + " | ".join(types) + " |", "|---|---|" + "---|" * len(types)]
    for (n, v), r in q.items():
        bt = r["conv_fp32vec_by_type"]
        out.append(f"| {n} | {v} | " + " | ".join(f3(bt.get(t, {}).get('R@5')) for t in types) + " |")

    sp = RES / "speed_embed.json"
    if sp.exists():
        s = json.loads(sp.read_text())
        out += ["", "## Embedding speed (container CPU, best of 3)", "",
                "Japanese segments of 20-60 chars (avg ~29 chars) sampled from conv_eval; n per row below. "
                "4-thread rows are unreliable: the container (4 vCPU) had load average 8-15 from other jobs.", "",
                "| model | ONNX | threads | batch | n | avg tokens | ms/seg | seg/s | 3,000 segs (s) |",
                "|---|---|---|---|---|---|---|---|---|"]
        for r in s["runs"]:
            out.append(f"| {r['model']} | {r['variant']} | {r['threads']} | {r['batch']} | {r.get('n_segs', 96)} | {r['avg_tokens']} "
                       f"| {r['ms_per_seg']} | {r['segs_per_s']} | {r['day_3000_s']} |")

    sn = RES / "search_numpy.json"
    if sn.exists():
        s = json.loads(sn.read_text())
        out += ["", f"## Brute-force search, numpy (dim {s['dim']}, top-{s['k']})", "",
                "| N | mode | threads | min ms | median ms |", "|---|---|---|---|---|"]
        for r in s["runs"]:
            out.append(f"| {r['n']:,} | {r['mode']} | {r['threads']} | {r['min_ms']} | {r['median_ms']} |")
        out += ["", "Storage (int8 + float32 scale): " +
                ", ".join(f"{int(k):,} → {v} MB" for k, v in s["storage_mb"].items())]
    for p in sorted(RES.glob("search_java_*.json")):
        s = json.loads(p.read_text())
        out += ["", f"## Brute-force search, Java {s['java']} (N={s['n']:,}, dim {s['dim']}, top-{s['k']})", "",
                "| variant | threads | min ms | median ms |", "|---|---|---|---|"]
        for r in s["runs"]:
            out.append(f"| {r['variant']} | {r['threads']} | {r['min_ms']} | {r['median_ms']} |")
    sq = RES / "sqlite_read.json"
    if sq.exists():
        s = json.loads(sq.read_text())
        out += ["", "## SQLite BLOB read (Python sqlite3, no cache)", "",
                f"N={s['n']:,} x {s['dim']}: DB {s['sqlite_db_mb']} MB ({s['bytes_per_row_sqlite']} B/row), "
                f"full SELECT of all BLOBs {s['sqlite_full_read_ms']} ms vs mmap flat file {s['mmap_open_touch_ms']} ms"]
    tc = RES / "tokenizer_check.json"
    if tc.exists():
        t = json.loads(tc.read_text())
        out += ["", "## Tokenizer re-implementation check (fraction of texts whose ids differ from tokenizer.json)", "",
                "| model | HF normalizer | plain NFKC | NFKC + whitespace | no normalizer | sentencepiece lib (pieces) |",
                "|---|---|---|---|---|---|"]
        for n, r in t.items():
            out.append(f"| {n} | {r['normalizer']} | {r['mismatch_nfkc']:.2%} | {r['mismatch_nfkc_ws']:.2%} "
                       f"| {r['mismatch_nonorm']:.2%} | {format(r['mismatch_spm_pieces'], '.2%') if 'mismatch_spm_pieces' in r else '-'} |")
    (RES / "summary.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
