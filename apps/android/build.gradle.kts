plugins {
    // applicationId, SDK levels, version (gradle.properties), Java, Compose, release: build-logic (#138)
    id("watchaudio.android.app")
    // libsherpa-onnx-jni.so without TTS (eSpeak NG, GPL-3.0) instead of the AAR's (#173)
    id("watchaudio.android.sherpa-onnx-jni")
}

android {
    namespace = "app.watchaudio.android"

    defaultConfig {
        minSdk = libs.versions.android.minSdk.get().toInt()
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        ndk {
            // Real phones (arm64) and the emulator (x86_64); sherpa-onnx ships ~30 MB per ABI.
            abiFilters += listOf("arm64-v8a", "x86_64")
        }
    }

    packaging {
        jniLibs {
            // sherpa-onnx's C/C++ API libraries; the Kotlin API only loads the JNI library (which
            // watchaudio.android.sherpa-onnx-jni replaces) and libonnxruntime.so.
            excludes += listOf("**/libsherpa-onnx-c-api.so", "**/libsherpa-onnx-cxx-api.so")
        }
    }

    // emulator.yml runs ReleaseAsrTest against the R8 release build (#78): with
    // `-Pwatchaudio.testBuildType=release` the instrumented test APK is built for it, and the app also
    // keeps what that test calls (generated by tools/release-test-keep/generate.sh). Without the
    // property the release APK is exactly the shipped one.
    val testBuildTypeName = providers.gradleProperty("watchaudio.testBuildType").getOrElse("debug")
    testBuildType = testBuildTypeName
    buildTypes.getByName("release") {
        if (testBuildTypeName == "release") proguardFiles("proguard-release-test.pro")
        testProguardFiles("proguard-test-rules.pro")
    }
}

dependencies {
    implementation(projects.shared.ui)
    implementation(projects.shared.protocol)
    implementation(projects.shared.db)
    implementation(projects.shared.pipeline)
    implementation(libs.androidx.activity.compose)
