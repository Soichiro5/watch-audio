#!/usr/bin/env bash
# Regenerates androidApp/proguard-release-test.pro: keep rules for every class and member of the app
# (our code and its libraries) that ReleaseAsrTest and its fixtures call, plus what the androidx.test
# runner needs from the app's libraries (#78). The test APK of a minified build is linked against the
# app's R8 output, so R8 must not remove what only the test uses. The rules are applied to the app
# only when it is built for that test (`-Pwatchaudio.testBuildType=release`), never to the shipped APK.
#
# Run it after changing ReleaseAsrTest or the fixtures it uses (TEST_CLASSES below):
#   tools/release-test-keep/generate.sh
# Uses R8's tracereferences from the Android SDK command-line tools.
set -euo pipefail

cd "$(dirname "$0")/../.."
ROOT=$PWD
TEST_CLASSES="ReleaseAsrTest SpeechFixtures PlaybackFixtures Evidence TestAudio SeededChunk"
OUT=androidApp/proguard-release-test.pro

SDK=${ANDROID_HOME:-$(sed -n 's/^sdk.dir=//p' local.properties 2>/dev/null)}
R8=$SDK/cmdline-tools/latest/lib/r8.jar
ANDROID_JAR=$(ls -d "$SDK"/platforms/android-*/android.jar | sort -V | tail -1)
[ -f "$R8" ] || { echo "r8.jar not found in $SDK/cmdline-tools/latest/lib" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# Runtime class jars of the app and of its androidTest APK, as R8 sees them.
cat > "$WORK/classpath.init.gradle.kts" <<'EOF'
allprojects {
    if (path == ":androidApp") {
        afterEvaluate {
            tasks.register("printReleaseTestClasspath") {
                fun jars(name: String) = configurations.getByName(name).incoming.artifactView {
                    attributes { attribute(Attribute.of("artifactType", String::class.java), "android-classes-jar") }
                }.files
                val app = jars("releaseRuntimeClasspath")
                val test = jars("releaseAndroidTestRuntimeClasspath")
                doLast {
                    app.forEach { println("APP_JAR $it") }
                    test.forEach { println("TEST_JAR $it") }
                }
            }
        }
    }
}
EOF
./gradlew --max-workers=2 --no-configuration-cache -q -Pwatchaudio.testBuildType=release -I "$WORK/classpath.init.gradle.kts" \
  :androidApp:compileReleaseKotlin :androidApp:compileReleaseAndroidTestKotlin :androidApp:printReleaseTestClasspath > "$WORK/classpath.txt"

KOTLINC=androidApp/build/intermediates/built_in_kotlinc
(cd "$KOTLINC/release/compileReleaseKotlin/classes" && zip -qr "$WORK/app.jar" .)
mkdir -p "$WORK/test"
for c in $TEST_CLASSES; do
  (cd "$KOTLINC/releaseAndroidTest/compileReleaseAndroidTestKotlin/classes" && cp --parents app/watchaudio/android/"$c"*.class "$WORK/test/")
done
(cd "$WORK/test" && zip -qr "$WORK/test.jar" .)

# Sources: the test path and the test-only libraries it runs on (androidx.test runner, JUnit, kotlin-test;
# not the Compose, UiAutomator, Espresso or WorkManager test libraries of the other tests); targets: the app.
{
  echo --source; echo "$WORK/test.jar"
  echo --target; echo "$WORK/app.jar"
  sed -n 's/^APP_JAR //p' "$WORK/classpath.txt" | sort -u > "$WORK/app-jars.txt"
  while read -r jar; do echo --target; echo "$jar"; done < "$WORK/app-jars.txt"
  sed -n 's/^TEST_JAR //p' "$WORK/classpath.txt" | sort -u | grep -vxFf "$WORK/app-jars.txt" |
    grep -vE '/(espresso-|ui-test|uiautomator-|work-testing-|kotlinx-coroutines-test)[^/]*$' | while read -r jar; do echo --source; echo "$jar"; done
} > "$WORK/args"

{
  echo "# GENERATED by tools/release-test-keep/generate.sh; do not edit by hand."
  echo "# Keeps what ReleaseAsrTest and its fixtures ($TEST_CLASSES) and the test runner use from the app."
  echo "# Only applied to the app built with -Pwatchaudio.testBuildType=release (emulator.yml, #78)."
} > "$WORK/rules.pro"
# References outside the app (e.g. the JUnit 3 classes of android.test) are reported as info, not errors.
java -cp "$R8" com.android.tools.r8.tracereferences.TraceReferences --keep-rules --allowobfuscation \
  --map-diagnostics error info --lib "$ANDROID_JAR" @"$WORK/args" --output "$WORK/traced.pro" > "$WORK/trace.log" 2>&1 ||
  { cat "$WORK/trace.log" >&2; exit 1; }
cat "$WORK/traced.pro" >> "$WORK/rules.pro"
mv "$WORK/rules.pro" "$ROOT/$OUT"
echo "wrote $OUT ($(grep -c '^-keep' "$ROOT/$OUT") keep rules)"
