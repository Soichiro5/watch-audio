package app.watchaudio.core.backup

import app.watchaudio.testing.TempDir
import java.io.File
import kotlin.io.encoding.Base64
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlinx.coroutines.test.runTest

/**
 * Keeps the checked-in backups under `testdata/backup/` and their embedded copies (read by
 * [BackupFixtureTest] on every platform) identical. With `UPDATE_BACKUP_FIXTURE=1`, it first
 * rewrites the v2 fixtures (`v2-full-with-audio`, `v2-diff-with-audio`) from the current writer;
 * the v1 fixture was written before diffs existed (#164) and is never rewritten.
 */
class BackupFixtureFileTest {
    // Gradle runs JVM tests with the module directory as the working directory.
    private val v1 = File(BackupFixture.V1_FILE)
    private val full = File(BackupFixture.FULL_FILE)
    private val diff = File(BackupFixture.DIFF_FILE)

    @Test
    fun filesMatchTheEmbeddedCopies() = runTest {
        if (System.getenv("UPDATE_BACKUP_FIXTURE") == "1") regenerate()
        assertContentEquals(v1.readBytes(), BackupFixture.v1, "${BackupFixture.V1_FILE} differs from BACKUP_FIXTURE_V1_BASE64")
        assertContentEquals(full.readBytes(), BackupFixture.full, "${BackupFixture.FULL_FILE} differs from BACKUP_FIXTURE_V2_FULL_BASE64")
        assertContentEquals(diff.readBytes(), BackupFixture.diff, "${BackupFixture.DIFF_FILE} differs from BACKUP_FIXTURE_V2_DIFF_BASE64")
    }

    private suspend fun regenerate() {
        val dir = TempDir("backup-fixture-gen")
        val written = try {
            BackupFixture.write(dir)
        } finally {
            dir.deleteRecursively()
        }
        full.parentFile.mkdirs()
        full.writeBytes(written.full)
        diff.writeBytes(written.diff)
        fun constant(name: String, file: String, bytes: ByteArray) =
            "/** Base64 of `$file` (common code cannot read files). */\ninternal const val $name =\n" +
                Base64.encode(bytes).chunked(100).joinToString(" +\n") { "    \"$it\"" } + "\n"
        File("src/sqliteTest/kotlin/app/watchaudio/core/backup/BackupFixtureV2Data.kt").writeText(
            "// Generated by BackupFixtureFileTest (UPDATE_BACKUP_FIXTURE=1); do not edit.\n" +
                "package app.watchaudio.core.backup\n\n" +
                constant("BACKUP_FIXTURE_V2_FULL_BASE64", BackupFixture.FULL_FILE, written.full) + "\n" +
                constant("BACKUP_FIXTURE_V2_DIFF_BASE64", BackupFixture.DIFF_FILE, written.diff),
        )
    }
}
