package app.watchaudio.core.backup

import app.watchaudio.testing.TempDir
import java.io.File
import kotlin.io.encoding.Base64
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlinx.coroutines.test.runTest

/**
 * Keeps `testdata/backup/v1-with-audio.wabackup` and its embedded copy ([BACKUP_FIXTURE_V1_BASE64],
 * read by [BackupFixtureTest] on every platform) identical. With `UPDATE_BACKUP_FIXTURE=1`, it
 * first rewrites both from the current writer.
 */
class BackupFixtureFileTest {
    // Gradle runs JVM tests with the module directory as the working directory.
    private val file = File(BackupFixture.FILE)

    @Test
    fun fileMatchesTheEmbeddedCopy() = runTest {
        if (System.getenv("UPDATE_BACKUP_FIXTURE") == "1") regenerate()
        assertContentEquals(file.readBytes(), BackupFixture.bytes, "${BackupFixture.FILE} differs from BACKUP_FIXTURE_V1_BASE64")
    }

    private suspend fun regenerate() {
        val dir = TempDir("backup-fixture-gen")
        val bytes = try {
            BackupFixture.write(dir)
        } finally {
            dir.deleteRecursively()
        }
        file.parentFile.mkdirs()
        file.writeBytes(bytes)
        val lines = Base64.encode(bytes).chunked(100).joinToString(" +\n") { "    \"$it\"" }
        File("src/sqliteTest/kotlin/app/watchaudio/core/backup/BackupFixtureData.kt").writeText(
            """
            |// Generated by BackupFixtureFileTest (UPDATE_BACKUP_FIXTURE=1); do not edit.
            |package app.watchaudio.core.backup
            |
            |/** Base64 of `testdata/backup/v1-with-audio.wabackup` (common code cannot read files). */
            |internal const val BACKUP_FIXTURE_V1_BASE64 =
            |
            """.trimMargin() + lines + "\n",
        )
    }
}
