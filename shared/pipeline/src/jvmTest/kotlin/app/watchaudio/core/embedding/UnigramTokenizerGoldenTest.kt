package app.watchaudio.core.embedding

import java.io.File
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/**
 * [UnigramTokenizer] gives exactly the ids of the Hugging Face `tokenizers` library for the
 * ruri-v3-30m tokenizer (#24), on the 960 texts of `testdata/embedding/ruri-tokenizer-golden.json`
 * (edge cases, the test-audio conversations, the embedding benchmark's queries and segments, joined
 * passages). Generated by `research/embedding-benchmark/scripts/make_tokenizer_fixture.py`.
 *
 * The committed subset tokenizer holds every piece that can match those texts, so its segmentation
 * equals the full vocabulary's; the full `tokenizer.json` (6.7 MB, downloaded by
 * `tools/harness/download-models.sh`) is also checked when it is present.
 */
class UnigramTokenizerGoldenTest {
    // Gradle runs JVM tests with the module directory as the working directory.
    private val golden = Json.parseToJsonElement(File("testdata/embedding/ruri-tokenizer-golden.json").readText())
        .jsonObject["texts"]!!.jsonArray.map { it.jsonObject }

    @Test
    fun subsetTokenizerMatchesTheLibrary() {
        val tokenizer = UnigramTokenizer.fromJson(File("testdata/embedding/ruri-tokenizer-subset.json").readText())
        assertEquals(960, golden.size)
        check(tokenizer, "subset_ids")
    }

    @Test
    fun fullTokenizerMatchesTheLibraryWhenDownloaded() {
        val file = File("../../tools/harness/models/${RuriV3.DIRECTORY}/${RuriV3.TOKENIZER_FILE}")
        if (!file.isFile) {
            println("skipped: ${file.path} not downloaded (tools/harness/download-models.sh)")
            return
        }
        val tokenizer = UnigramTokenizer.fromJson(file.readText())
        assertEquals(102_400, tokenizer.vocabularySize)
        check(tokenizer, "ids")
    }

    @Test
    fun truncationKeepsTheSpecialTokens() {
        val tokenizer = UnigramTokenizer.fromJson(File("testdata/embedding/ruri-tokenizer-subset.json").readText())
        val long = golden.first { it["text"]!!.jsonPrimitive.content == "の".repeat(300) }
        val expected = long["subset_ids"]!!.jsonArray.map { it.jsonPrimitive.int }
        val cut = tokenizer.encode("の".repeat(300), maxLength = 10)
        assertEquals(10, cut.size)
        assertContentEquals(expected.take(9) + expected.last(), cut.toList())
        assertTrue(expected.size > 10)
    }

    private fun check(tokenizer: UnigramTokenizer, key: String) {
        val mismatches = golden.filterNot { entry ->
            val text = entry["text"]!!.jsonPrimitive.content
            entry[key]!!.jsonArray.map { it.jsonPrimitive.int } == tokenizer.encode(text).toList()
        }
        assertTrue(mismatches.isEmpty(), "${mismatches.size} mismatches, first: ${mismatches.firstOrNull()?.get("text")}")
    }
}
